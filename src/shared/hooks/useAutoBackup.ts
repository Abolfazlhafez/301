import { useEffect, useRef } from "react";
import { backupService } from "../../core/services/backupService";
import { useAppLifecycle } from "./useAppLifecycle";

/**
 * در هر بار باز شدن اپ، و همچنین هر بار که اپ از پس‌زمینه به پیش‌زمینه
 * برمی‌گردد (Resume)، بررسی می‌کند که آیا زمان بکاپ خودکار دوره‌ای فرا
 * رسیده است یا نه (بر اساس تنظیمات کاربر: فعال/غیرفعال، فاصلهٔ زمانی).
 * در صورت لزوم، یک بکاپ جدید در حافظهٔ داخلی اپ می‌سازد و نسخه‌های اضافی
 * قدیمی را حذف می‌کند. کاملاً آفلاین و بدون نیاز به تعامل کاربر.
 *
 * قبل از افزوده‌شدن useAppLifecycle، این بررسی فقط یک‌بار در mount اولیهٔ
 * برنامه اجرا می‌شد — یعنی کاربری که برنامه را روزها باز نگه می‌داشت و
 * فقط بین اپ‌ها سوییچ می‌کرد (بدون هرگز کاملاً بستن/باز کردن از صفر)،
 * ممکن بود هرگز بکاپ خودکار دورهٔ بعدی را دریافت نکند. حالا با هر
 * برگشت از پس‌زمینه هم دوباره چک می‌شود — دقیقاً هم‌راستا با الزام
 * پرامپت اصلی دربارهٔ «اجرای کارهای دوره‌ای» حتی وقتی برنامه کاملاً
 * بسته نشده، فقط به پس‌زمینه رفته است.
 *
 * خطاهای احتمالی (مثلاً کمبود فضا) بی‌صدا نادیده گرفته می‌شوند تا مانع
 * بالا آمدن عادی برنامه نشوند؛ بکاپ خودکار یک قابلیت کمکی است، نه بخشی
 * حیاتی از مسیر اجرای برنامه.
 */
export function useAutoBackup(): void {
  const hasRun = useRef(false);

  function checkAndRunIfDue() {
    backupService.runAutoBackupIfDue().catch(() => {
      // بی‌صدا نادیده گرفته می‌شود؛ بکاپ خودکار نباید تجربهٔ کاربر را مختل کند.
    });
  }

  useEffect(() => {
    if (hasRun.current) return;
    hasRun.current = true;
    checkAndRunIfDue();
  }, []);

  useAppLifecycle({ onResume: checkAndRunIfDue });
}
