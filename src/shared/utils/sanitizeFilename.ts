/**
 * یک رشته را برای استفادهٔ امن به‌عنوان نام فایل (روی اندروید و مرورگر) آماده
 * می‌کند. کاراکترهایی که در مسیر فایل معنای خاص دارند یا در ویندوز/اندروید
 * مجاز نیستند با «-» جایگزین می‌شوند.
 *
 * چرا لازم است: خروجی‌های CSV و عکس در این اپ معمولاً نام فایل را از تاریخ
 * شمسی (مثل «۱۴۰۵/۰۵/۰۱») یا نام آزاد کاربر (نام صندوق، نام نیرو) می‌سازند.
 * اگر «/» در نام فایل باقی بماند، پلاگین Filesystem آن را بخشی از مسیر
 * (زیرپوشه) تفسیر می‌کند و چون آن زیرپوشه از قبل وجود ندارد، خطای
 * «Parent folder doesn't exist» می‌دهد. این تابع دقیقاً همین مشکل را حل
 * می‌کند، بدون این‌که خوانایی نام فایل را از بین ببرد (مثلاً
 * «۱۴۰۵/۰۵/۰۱» تبدیل می‌شود به «۱۴۰۵-۰۵-۰۱»، نه چیزی که معنایش را گم کند).
 */
export function sanitizeFilename(name: string): string {
  return name
    .replace(/[/\\:*?"<>|]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^[-\s]+|[-\s]+$/g, "")
    .trim();
}
